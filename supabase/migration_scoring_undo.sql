begin;

alter table public.game_events
  add column if not exists event_order bigint generated by default as identity,
  add column if not exists home_delta integer not null default 0,
  add column if not exists away_delta integer not null default 0,
  add column if not exists undone_at timestamptz,
  add column if not exists undo_of uuid references public.game_events(id);

create unique index if not exists game_events_event_order_idx
  on public.game_events (event_order);

create index if not exists game_events_game_order_idx
  on public.game_events (game_id, event_order desc);

create or replace function public.update_game(
  p_code text,
  p_manager_key text,
  p_home_delta integer,
  p_away_delta integer,
  p_status text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  stored_key_hash bytea;
  target_game_id uuid;
  current_home_team text;
  current_away_team text;
  current_home_score integer;
  current_away_score integer;
  current_status text;
  new_home_score integer;
  new_away_score integer;
begin
  if p_home_delta not between -10 and 10 or p_away_delta not between -10 and 10 then
    raise exception using errcode = '22023', message = 'Score changes must be between -10 and 10 points';
  end if;

  if p_status not in ('LIVE', 'FINAL') then
    raise exception using errcode = '22023', message = 'Invalid game status';
  end if;

  select id, home_team, away_team, home_score, away_score, status
  into target_game_id, current_home_team, current_away_team, current_home_score, current_away_score, current_status
  from public.games
  where code = p_code
  for update;

  if target_game_id is null then
    raise exception using errcode = '42501', message = 'Invalid manager key';
  end if;

  select key_hash
  into stored_key_hash
  from public.game_manager_keys
  where game_manager_keys.game_id = target_game_id;

  if stored_key_hash is null
    or stored_key_hash <> extensions.digest(pg_catalog.convert_to(p_manager_key, 'UTF8'), 'sha256') then
    raise exception using errcode = '42501', message = 'Invalid manager key';
  end if;

  if current_status = 'FINAL' and (p_home_delta <> 0 or p_away_delta <> 0) then
    raise exception using errcode = '22023', message = 'Resume the game before changing the score';
  end if;

  new_home_score := current_home_score + p_home_delta;
  new_away_score := current_away_score + p_away_delta;

  if new_home_score < 0 or new_away_score < 0 then
    raise exception using errcode = '22023', message = 'Scores cannot be negative';
  end if;

  update public.games
  set home_score = new_home_score,
      away_score = new_away_score,
      status = p_status,
      updated_at = pg_catalog.now()
  where id = target_game_id;

  if current_status <> p_status then
    insert into public.game_events (game_id, event_type, team, home_score, away_score, message)
    values (
      target_game_id,
      'STATUS',
      null,
      new_home_score,
      new_away_score,
      case when p_status = 'FINAL'
        then 'Game marked as FINAL (' || new_home_score || ' - ' || new_away_score || ')'
        else 'Game resumed to LIVE'
      end
    );
  end if;

  if p_home_delta <> 0 then
    insert into public.game_events (
      game_id, event_type, team, home_delta, away_delta, home_score, away_score, message
    )
    values (
      target_game_id,
      'SCORE',
      'home',
      p_home_delta,
      0,
      new_home_score,
      new_away_score,
      case when p_home_delta > 0
        then '+' || p_home_delta || case when p_home_delta = 1 then ' point for ' else ' points for ' end || current_home_team || ' (' || new_home_score || ' - ' || new_away_score || ')'
        else p_home_delta || case when p_home_delta = -1 then ' point for ' else ' points for ' end || current_home_team || ' (' || new_home_score || ' - ' || new_away_score || ')'
      end
    );
  end if;

  if p_away_delta <> 0 then
    insert into public.game_events (
      game_id, event_type, team, home_delta, away_delta, home_score, away_score, message
    )
    values (
      target_game_id,
      'SCORE',
      'away',
      0,
      p_away_delta,
      new_home_score,
      new_away_score,
      case when p_away_delta > 0
        then '+' || p_away_delta || case when p_away_delta = 1 then ' point for ' else ' points for ' end || current_away_team || ' (' || new_home_score || ' - ' || new_away_score || ')'
        else p_away_delta || case when p_away_delta = -1 then ' point for ' else ' points for ' end || current_away_team || ' (' || new_home_score || ' - ' || new_away_score || ')'
      end
    );
  end if;

  return true;
end;
$$;

create or replace function public.undo_last_score(
  p_code text,
  p_manager_key text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  stored_key_hash bytea;
  target_game_id uuid;
  target_event_id uuid;
  target_home_delta integer;
  target_away_delta integer;
  current_home_score integer;
  current_away_score integer;
  latest_reset_order bigint;
  new_home_score integer;
  new_away_score integer;
begin
  select id, home_score, away_score
  into target_game_id, current_home_score, current_away_score
  from public.games
  where code = p_code
  for update;

  if target_game_id is null then
    raise exception using errcode = '42501', message = 'Invalid manager key';
  end if;

  select key_hash
  into stored_key_hash
  from public.game_manager_keys
  where game_manager_keys.game_id = target_game_id;

  if stored_key_hash is null
    or stored_key_hash <> extensions.digest(pg_catalog.convert_to(p_manager_key, 'UTF8'), 'sha256') then
    raise exception using errcode = '42501', message = 'Invalid manager key';
  end if;

  select coalesce(max(event_order), 0)
  into latest_reset_order
  from public.game_events
  where game_id = target_game_id
    and event_type = 'RESET';

  select id, home_delta, away_delta
  into target_event_id, target_home_delta, target_away_delta
  from public.game_events
  where game_id = target_game_id
    and event_type = 'SCORE'
    and undone_at is null
    and event_order > latest_reset_order
    and (home_delta <> 0 or away_delta <> 0)
  order by event_order desc
  limit 1
  for update;

  if target_event_id is null then
    raise exception using errcode = '22023', message = 'There is no score action to undo';
  end if;

  new_home_score := current_home_score - target_home_delta;
  new_away_score := current_away_score - target_away_delta;

  if new_home_score < 0 or new_away_score < 0 then
    raise exception using errcode = '22023', message = 'Cannot undo: the current score has changed';
  end if;

  update public.games
  set home_score = new_home_score,
      away_score = new_away_score,
      updated_at = pg_catalog.now()
  where id = target_game_id;

  update public.game_events
  set undone_at = pg_catalog.now()
  where id = target_event_id;

  insert into public.game_events (
    game_id,
    event_type,
    team,
    home_delta,
    away_delta,
    undo_of,
    home_score,
    away_score,
    message
  )
  values (
    target_game_id,
    'UNDO',
    case when target_home_delta <> 0 then 'home' else 'away' end,
    -target_home_delta,
    -target_away_delta,
    target_event_id,
    new_home_score,
    new_away_score,
    'Undid the last score action (' || new_home_score || ' - ' || new_away_score || ')'
  );

  return true;
end;
$$;

revoke all on function public.undo_last_score(text, text) from public;
grant execute on function public.undo_last_score(text, text) to anon, authenticated;

notify pgrst, 'reload schema';

commit;
