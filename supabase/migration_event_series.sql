create or replace function public.create_scoreboard_event(
  p_code text,
  p_title text
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception using errcode = '42501', message = 'Sign in to create an event';
  end if;

  if p_code !~ '^[A-Z0-9]{10}$' then
    raise exception using errcode = '22023', message = 'Invalid event code';
  end if;

  if pg_catalog.char_length(pg_catalog.btrim(p_title)) not between 1 and 48 then
    raise exception using errcode = '22023', message = 'Event name must be between 1 and 48 characters';
  end if;

  insert into public.scoreboard_events (code, title, owner_id)
  values (p_code, pg_catalog.btrim(p_title), auth.uid());

  return p_code;
end;
$$;

create or replace function public.create_event_game(
  p_event_code text,
  p_code text,
  p_home_team text,
  p_away_team text,
  p_home_color text,
  p_away_color text,
  p_home_logo text,
  p_away_logo text
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_event_id uuid;
  next_queue_order integer;
  new_game_id uuid;
begin
  select id into target_event_id
  from public.scoreboard_events
  where code = p_event_code
    and owner_id = auth.uid()
  for update;

  if target_event_id is null then
    raise exception using errcode = '42501', message = 'Event not found or access denied';
  end if;

  if p_code !~ '^[A-Z0-9]{10}$' then
    raise exception using errcode = '22023', message = 'Invalid game code';
  end if;

  if pg_catalog.char_length(pg_catalog.btrim(p_home_team)) not between 1 and 24
    or pg_catalog.char_length(pg_catalog.btrim(p_away_team)) not between 1 and 24 then
    raise exception using errcode = '22023', message = 'Team names must be between 1 and 24 characters';
  end if;

  select coalesce(max(queue_order), 0) + 1
  into next_queue_order
  from public.games
  where event_id = target_event_id;

  insert into public.games (
    event_id, queue_order, code, home_team, away_team,
    home_color, away_color, home_logo, away_logo, status
  )
  values (
    target_event_id, next_queue_order, p_code,
    pg_catalog.btrim(p_home_team), pg_catalog.btrim(p_away_team),
    coalesce(nullif(pg_catalog.btrim(p_home_color), ''), '#2563eb'),
    coalesce(nullif(pg_catalog.btrim(p_away_color), ''), '#dc2626'),
    coalesce(nullif(pg_catalog.btrim(p_home_logo), ''), '🏀'),
    coalesce(nullif(pg_catalog.btrim(p_away_logo), ''), '⚡'),
    'UPCOMING'
  )
  returning id into new_game_id;

  insert into public.game_events (game_id, event_type, team, home_score, away_score, message)
  values (
    new_game_id,
    'START',
    null,
    0,
    0,
    'Game queued: ' || pg_catalog.btrim(p_home_team) || ' vs ' || pg_catalog.btrim(p_away_team)
  );

  return p_code;
end;
$$;

create or replace function public.start_event_game(
  p_event_code text,
  p_game_id uuid
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_event_id uuid;
  active_game_id uuid;
  active_game_status text;
  target_game_status text;
begin
  select id, current_game_id
  into target_event_id, active_game_id
  from public.scoreboard_events
  where code = p_event_code
    and owner_id = auth.uid()
  for update;

  if target_event_id is null then
    raise exception using errcode = '42501', message = 'Event not found or access denied';
  end if;

  if active_game_id is not null then
    select status into active_game_status
    from public.games
    where id = active_game_id;

    if active_game_status <> 'FINAL' then
      raise exception using errcode = '22023', message = 'Finish the current game before starting the next one';
    end if;
  end if;

  select status into target_game_status
  from public.games
  where id = p_game_id
    and event_id = target_event_id
  for update;

  if target_game_status is distinct from 'UPCOMING' then
    raise exception using errcode = '22023', message = 'This game is not waiting to start';
  end if;

  update public.games
  set status = 'LIVE',
      updated_at = pg_catalog.now()
  where id = p_game_id;

  update public.scoreboard_events
  set current_game_id = p_game_id,
      updated_at = pg_catalog.now()
  where id = target_event_id;

  insert into public.game_events (game_id, event_type, team, home_score, away_score, message)
  select id, 'STATUS', null, home_score, away_score, 'Game started'
  from public.games
  where id = p_game_id;

  return true;
end;
$$;

create or replace function public.verify_event_game_owner(p_code text)
returns boolean
language sql
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.games as game
    join public.scoreboard_events as scoreboard_event on scoreboard_event.id = game.event_id
    where game.code = p_code
      and scoreboard_event.owner_id = auth.uid()
  );
$$;

create or replace function public.update_event_game(
  p_code text,
  p_home_delta integer,
  p_away_delta integer,
  p_status text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_game_id uuid;
  current_home_team text;
  current_away_team text;
  current_home_score integer;
  current_away_score integer;
  current_status text;
  new_home_score integer;
  new_away_score integer;
begin
  if p_home_delta not between -10 and 10 or p_away_delta not between -10 and 10 then
    raise exception using errcode = '22023', message = 'Score changes must be between -10 and 10 points';
  end if;

  if p_status not in ('LIVE', 'FINAL') then
    raise exception using errcode = '22023', message = 'Invalid game status';
  end if;

  select game.id, game.home_team, game.away_team, game.home_score, game.away_score, game.status
  into target_game_id, current_home_team, current_away_team, current_home_score, current_away_score, current_status
  from public.games as game
  join public.scoreboard_events as scoreboard_event on scoreboard_event.id = game.event_id
  where game.code = p_code
    and scoreboard_event.owner_id = auth.uid()
  for update of game;

  if target_game_id is null then
    raise exception using errcode = '42501', message = 'Event game not found or access denied';
  end if;

  if current_status = 'UPCOMING' then
    raise exception using errcode = '22023', message = 'Start the game before changing the score';
  end if;

  if current_status = 'FINAL' and (p_home_delta <> 0 or p_away_delta <> 0) then
    raise exception using errcode = '22023', message = 'Resume the game before changing the score';
  end if;

  new_home_score := current_home_score + p_home_delta;
  new_away_score := current_away_score + p_away_delta;

  if new_home_score < 0 or new_away_score < 0 then
    raise exception using errcode = '22023', message = 'Scores cannot be negative';
  end if;

  update public.games
  set home_score = new_home_score,
      away_score = new_away_score,
      status = p_status,
      updated_at = pg_catalog.now()
  where id = target_game_id;

  if current_status <> p_status then
    insert into public.game_events (game_id, event_type, team, home_score, away_score, message)
    values (
      target_game_id, 'STATUS', null, new_home_score, new_away_score,
      case when p_status = 'FINAL'
        then 'Game marked as FINAL (' || new_home_score || ' - ' || new_away_score || ')'
        else 'Game resumed to LIVE'
      end
    );
  end if;

  if p_home_delta <> 0 then
    insert into public.game_events (game_id, event_type, team, home_delta, away_delta, home_score, away_score, message)
    values (
      target_game_id, 'SCORE', 'home', p_home_delta, 0, new_home_score, new_away_score,
      case when p_home_delta > 0
        then '+' || p_home_delta || case when p_home_delta = 1 then ' point for ' else ' points for ' end || current_home_team
        else p_home_delta || case when p_home_delta = -1 then ' point for ' else ' points for ' end || current_home_team
      end || ' (' || new_home_score || ' - ' || new_away_score || ')'
    );
  end if;

  if p_away_delta <> 0 then
    insert into public.game_events (game_id, event_type, team, home_delta, away_delta, home_score, away_score, message)
    values (
      target_game_id, 'SCORE', 'away', 0, p_away_delta, new_home_score, new_away_score,
      case when p_away_delta > 0
        then '+' || p_away_delta || case when p_away_delta = 1 then ' point for ' else ' points for ' end || current_away_team
        else p_away_delta || case when p_away_delta = -1 then ' point for ' else ' points for ' end || current_away_team
      end || ' (' || new_home_score || ' - ' || new_away_score || ')'
    );
  end if;

  return true;
end;
$$;

create or replace function public.undo_event_game_score(p_code text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_game_id uuid;
  target_event_id uuid;
  target_home_delta integer;
  target_away_delta integer;
  current_home_score integer;
  current_away_score integer;
  latest_reset_order bigint;
  new_home_score integer;
  new_away_score integer;
begin
  select game.id, game.home_score, game.away_score
  into target_game_id, current_home_score, current_away_score
  from public.games as game
  join public.scoreboard_events as scoreboard_event on scoreboard_event.id = game.event_id
  where game.code = p_code
    and scoreboard_event.owner_id = auth.uid()
  for update of game;

  if target_game_id is null then
    raise exception using errcode = '42501', message = 'Event game not found or access denied';
  end if;

  select coalesce(max(event_order), 0)
  into latest_reset_order
  from public.game_events
  where game_id = target_game_id
    and event_type = 'RESET';

  select id, home_delta, away_delta
  into target_event_id, target_home_delta, target_away_delta
  from public.game_events
  where game_id = target_game_id
    and event_type = 'SCORE'
    and undone_at is null
    and event_order > latest_reset_order
    and (home_delta <> 0 or away_delta <> 0)
  order by event_order desc
  limit 1
  for update;

  if target_event_id is null then
    raise exception using errcode = '22023', message = 'There is no score action to undo';
  end if;

  new_home_score := current_home_score - target_home_delta;
  new_away_score := current_away_score - target_away_delta;

  if new_home_score < 0 or new_away_score < 0 then
    raise exception using errcode = '22023', message = 'Cannot undo: the current score has changed';
  end if;

  update public.games
  set home_score = new_home_score,
      away_score = new_away_score,
      updated_at = pg_catalog.now()
  where id = target_game_id;

  update public.game_events
  set undone_at = pg_catalog.now()
  where id = target_event_id;

  insert into public.game_events (
    game_id, event_type, team, home_delta, away_delta, undo_of,
    home_score, away_score, message
  )
  values (
    target_game_id,
    'UNDO',
    case when target_home_delta <> 0 then 'home' else 'away' end,
    -target_home_delta,
    -target_away_delta,
    target_event_id,
    new_home_score,
    new_away_score,
    'Undid the last score action (' || new_home_score || ' - ' || new_away_score || ')'
  );

  return true;
end;
$$;

create or replace function public.reset_event_game_score(p_code text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_game_id uuid;
begin
  select game.id into target_game_id
  from public.games as game
  join public.scoreboard_events as scoreboard_event on scoreboard_event.id = game.event_id
  where game.code = p_code
    and scoreboard_event.owner_id = auth.uid()
  for update of game;

  if target_game_id is null then
    raise exception using errcode = '42501', message = 'Event game not found or access denied';
  end if;

  update public.games
  set home_score = 0, away_score = 0, updated_at = pg_catalog.now()
  where id = target_game_id;

  insert into public.game_events (game_id, event_type, team, home_score, away_score, message)
  values (target_game_id, 'RESET', null, 0, 0, 'Score reset to 0 - 0');

  return true;
end;
$$;

