create extension if not exists pgcrypto with schema extensions;

create table if not exists public.games (
  id uuid primary key default gen_random_uuid(),
  code text not null unique check (code ~ '^[A-Z0-9]{10}$'),
  home_team text not null check (char_length(home_team) between 1 and 24),
  away_team text not null check (char_length(away_team) between 1 and 24),
  home_color text not null default '#2563eb',
  away_color text not null default '#dc2626',
  home_logo text not null default '🏀',
  away_logo text not null default '⚡',
  home_score integer not null default 0 check (home_score >= 0),
  away_score integer not null default 0 check (away_score >= 0),
  status text not null default 'LIVE' check (status in ('LIVE', 'FINAL')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.game_manager_keys (
  game_id uuid primary key references public.games(id) on delete cascade,
  key_hash bytea not null
);

create table if not exists public.game_events (
  id uuid primary key default gen_random_uuid(),
  event_order bigint generated by default as identity unique,
  game_id uuid not null references public.games(id) on delete cascade,
  event_type text not null,
  team text check (team in ('home', 'away', null)),
  home_delta integer not null default 0,
  away_delta integer not null default 0,
  undone_at timestamptz,
  undo_of uuid references public.game_events(id),
  home_score integer not null,
  away_score integer not null,
  message text not null,
  created_at timestamptz not null default now()
);

create index if not exists game_events_game_order_idx
  on public.game_events (game_id, event_order desc);

alter table public.games enable row level security;
alter table public.game_manager_keys enable row level security;
alter table public.game_events enable row level security;

drop policy if exists "Anyone can view game scores" on public.games;
create policy "Anyone can view game scores"
  on public.games
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can view game events" on public.game_events;
create policy "Anyone can view game events"
  on public.game_events
  for select
  to anon, authenticated
  using (true);

revoke all on table public.games, public.game_manager_keys, public.game_events from public, anon, authenticated;
grant select on table public.games, public.game_events to anon, authenticated;

create or replace function public.create_game(
  p_code text,
  p_home_team text,
  p_away_team text,
  p_manager_key text,
  p_home_color text default '#2563eb',
  p_away_color text default '#dc2626',
  p_home_logo text default '🏀',
  p_away_logo text default '⚡'
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_game_id uuid;
  v_home_color text;
  v_away_color text;
  v_home_logo text;
  v_away_logo text;
begin
  if p_code !~ '^[A-Z0-9]{10}$' then
    raise exception using errcode = '22023', message = 'Invalid game code';
  end if;

  if pg_catalog.char_length(pg_catalog.btrim(p_home_team)) not between 1 and 24
    or pg_catalog.char_length(pg_catalog.btrim(p_away_team)) not between 1 and 24 then
    raise exception using errcode = '22023', message = 'Team names must be between 1 and 24 characters';
  end if;

  if pg_catalog.char_length(p_manager_key) < 32 then
    raise exception using errcode = '22023', message = 'Invalid manager key';
  end if;

  v_home_color := coalesce(nullif(pg_catalog.btrim(p_home_color), ''), '#2563eb');
  v_away_color := coalesce(nullif(pg_catalog.btrim(p_away_color), ''), '#dc2626');
  v_home_logo := coalesce(nullif(pg_catalog.btrim(p_home_logo), ''), '🏀');
  v_away_logo := coalesce(nullif(pg_catalog.btrim(p_away_logo), ''), '⚡');

  insert into public.games (
    code,
    home_team,
    away_team,
    home_color,
    away_color,
    home_logo,
    away_logo
  )
  values (
    p_code,
    pg_catalog.btrim(p_home_team),
    pg_catalog.btrim(p_away_team),
    v_home_color,
    v_away_color,
    v_home_logo,
    v_away_logo
  )
  returning id into new_game_id;

  insert into public.game_manager_keys (game_id, key_hash)
  values (
    new_game_id,
    extensions.digest(pg_catalog.convert_to(p_manager_key, 'UTF8'), 'sha256')
  );

  insert into public.game_events (game_id, event_type, team, home_score, away_score, message)
  values (
    new_game_id,
    'START',
    null,
    0,
    0,
    'Game started: ' || pg_catalog.btrim(p_home_team) || ' vs ' || pg_catalog.btrim(p_away_team)
  );

  return p_code;
end;
$$;

create or replace function public.verify_manager_key(
  p_code text,
  p_manager_key text
)
returns boolean
language sql
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.games as game
    join public.game_manager_keys as manager_key on manager_key.game_id = game.id
    where game.code = p_code
      and manager_key.key_hash = extensions.digest(pg_catalog.convert_to(p_manager_key, 'UTF8'), 'sha256')
  );
$$;

create or replace function public.update_game(
  p_code text,
  p_manager_key text,
  p_home_delta integer,
  p_away_delta integer,
  p_status text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  stored_key_hash bytea;
  target_game_id uuid;
  current_home_team text;
  current_away_team text;
  current_home_score integer;
  current_away_score integer;
  current_status text;
  new_home_score integer;
  new_away_score integer;
begin
  if p_home_delta not between -10 and 10 or p_away_delta not between -10 and 10 then
    raise exception using errcode = '22023', message = 'Score changes must be between -10 and 10 points';
  end if;

  if p_status not in ('LIVE', 'FINAL') then
    raise exception using errcode = '22023', message = 'Invalid game status';
  end if;

  select id, home_team, away_team, home_score, away_score, status
  into target_game_id, current_home_team, current_away_team, current_home_score, current_away_score, current_status
  from public.games
  where code = p_code
  for update;

  if target_game_id is null then
    raise exception using errcode = '42501', message = 'Invalid manager key';
  end if;

  select key_hash
  into stored_key_hash
  from public.game_manager_keys
  where game_manager_keys.game_id = target_game_id;

  if stored_key_hash is null
    or stored_key_hash <> extensions.digest(pg_catalog.convert_to(p_manager_key, 'UTF8'), 'sha256') then
    raise exception using errcode = '42501', message = 'Invalid manager key';
  end if;

  if current_status = 'FINAL' and (p_home_delta <> 0 or p_away_delta <> 0) then
    raise exception using errcode = '22023', message = 'Resume the game before changing the score';
  end if;

  new_home_score := current_home_score + p_home_delta;
  new_away_score := current_away_score + p_away_delta;

  if new_home_score < 0 or new_away_score < 0 then
    raise exception using errcode = '22023', message = 'Scores cannot be negative';
  end if;

  update public.games
  set home_score = new_home_score,
      away_score = new_away_score,
      status = p_status,
      updated_at = pg_catalog.now()
  where code = p_code;

  if current_status <> p_status then
    insert into public.game_events (game_id, event_type, team, home_score, away_score, message)
    values (
      target_game_id,
      'STATUS',
      null,
      new_home_score,
      new_away_score,
      case when p_status = 'FINAL'
        then 'Game marked as FINAL (' || new_home_score || ' - ' || new_away_score || ')'
        else 'Game resumed to LIVE'
      end
    );
  end if;

  if p_home_delta <> 0 then
    insert into public.game_events (game_id, event_type, team, home_delta, away_delta, home_score, away_score, message)
    values (
      target_game_id,
      'SCORE',
      'home',
      p_home_delta,
      0,
      new_home_score,
      new_away_score,
      case when p_home_delta > 0
        then '+' || p_home_delta || case when p_home_delta = 1 then ' point for ' else ' points for ' end || current_home_team || ' (' || new_home_score || ' - ' || new_away_score || ')'
        else p_home_delta || case when p_home_delta = -1 then ' point for ' else ' points for ' end || current_home_team || ' (' || new_home_score || ' - ' || new_away_score || ')'
      end
    );
  end if;

  if p_away_delta <> 0 then
    insert into public.game_events (game_id, event_type, team, home_delta, away_delta, home_score, away_score, message)
    values (
      target_game_id,
      'SCORE',
      'away',
      0,
      p_away_delta,
      new_home_score,
      new_away_score,
      case when p_away_delta > 0
        then '+' || p_away_delta || case when p_away_delta = 1 then ' point for ' else ' points for ' end || current_away_team || ' (' || new_home_score || ' - ' || new_away_score || ')'
        else p_away_delta || case when p_away_delta = -1 then ' point for ' else ' points for ' end || current_away_team || ' (' || new_home_score || ' - ' || new_away_score || ')'
      end
    );
  end if;

  return true;
end;
$$;

create or replace function public.undo_last_score(
  p_code text,
  p_manager_key text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  stored_key_hash bytea;
  target_game_id uuid;
  target_event_id uuid;
  target_home_delta integer;
  target_away_delta integer;
  current_home_score integer;
  current_away_score integer;
  latest_reset_order bigint;
  new_home_score integer;
  new_away_score integer;
begin
  select id, home_score, away_score
  into target_game_id, current_home_score, current_away_score
  from public.games
  where code = p_code
  for update;

  if target_game_id is null then
    raise exception using errcode = '42501', message = 'Invalid manager key';
  end if;

  select key_hash
  into stored_key_hash
  from public.game_manager_keys
  where game_manager_keys.game_id = target_game_id;

  if stored_key_hash is null
    or stored_key_hash <> extensions.digest(pg_catalog.convert_to(p_manager_key, 'UTF8'), 'sha256') then
    raise exception using errcode = '42501', message = 'Invalid manager key';
  end if;

  select coalesce(max(event_order), 0)
  into latest_reset_order
  from public.game_events
  where game_id = target_game_id
    and event_type = 'RESET';

  select id, home_delta, away_delta
  into target_event_id, target_home_delta, target_away_delta
  from public.game_events
  where game_id = target_game_id
    and event_type = 'SCORE'
    and undone_at is null
    and event_order > latest_reset_order
    and (home_delta <> 0 or away_delta <> 0)
  order by event_order desc
  limit 1
  for update;

  if target_event_id is null then
    raise exception using errcode = '22023', message = 'There is no score action to undo';
  end if;

  new_home_score := current_home_score - target_home_delta;
  new_away_score := current_away_score - target_away_delta;

  if new_home_score < 0 or new_away_score < 0 then
    raise exception using errcode = '22023', message = 'Cannot undo: the current score has changed';
  end if;

  update public.games
  set home_score = new_home_score,
      away_score = new_away_score,
      updated_at = pg_catalog.now()
  where id = target_game_id;

  update public.game_events
  set undone_at = pg_catalog.now()
  where id = target_event_id;

  insert into public.game_events (
    game_id,
    event_type,
    team,
    home_delta,
    away_delta,
    undo_of,
    home_score,
    away_score,
    message
  )
  values (
    target_game_id,
    'UNDO',
    case when target_home_delta <> 0 then 'home' else 'away' end,
    -target_home_delta,
    -target_away_delta,
    target_event_id,
    new_home_score,
    new_away_score,
    'Undid the last score action (' || new_home_score || ' - ' || new_away_score || ')'
  );

  return true;
end;
$$;

create or replace function public.reset_game_score(
  p_code text,
  p_manager_key text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  stored_key_hash bytea;
  target_game_id uuid;
begin
  select id
  into target_game_id
  from public.games
  where code = p_code
  for update;

  if target_game_id is null then
    raise exception using errcode = '42501', message = 'Invalid manager key';
  end if;

  select key_hash
  into stored_key_hash
  from public.game_manager_keys
  where game_manager_keys.game_id = target_game_id;

  if stored_key_hash is null
    or stored_key_hash <> extensions.digest(pg_catalog.convert_to(p_manager_key, 'UTF8'), 'sha256') then
    raise exception using errcode = '42501', message = 'Invalid manager key';
  end if;

  update public.games
  set home_score = 0,
      away_score = 0,
      updated_at = pg_catalog.now()
  where code = p_code;

  insert into public.game_events (game_id, event_type, team, home_score, away_score, message)
  values (
    target_game_id,
    'RESET',
    null,
    0,
    0,
    'Score reset to 0 - 0'
  );

  return true;
end;
$$;

